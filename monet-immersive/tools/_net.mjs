import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/local/bin/google-chrome', args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox'] });
const p = await b.newPage();
p.on('pageerror', e => console.log('ERR', e.message));
p.on('console', m => console.log('LOG', m.text().slice(0, 200)));
p.on('requestfailed', r => console.log('FAIL', r.url(), r.failure()?.errorText));
p.on('response', r => r.status() >= 300 && console.log('HTTP', r.status(), r.url()));
await p.goto(process.argv[2], { waitUntil: 'load', timeout: 120000 });
await new Promise(r => setTimeout(r, 40000));
console.log('ready=', await p.evaluate(() => window.__ready), 'loader=', await p.evaluate(() => document.querySelector('#loader')?.textContent?.trim().slice(0, 80)));
await b.close();
